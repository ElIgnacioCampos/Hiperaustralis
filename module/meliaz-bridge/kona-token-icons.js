Hooks.once("ready", () => {
  konaTokenIconDebug("módulo cargado; banco disponible", {
    moduleActive: Boolean(game.modules?.get?.(KONA_TOKEN_ICON_MODULE_ID)?.active),
    foundryVersion: game.version ?? game.release?.version ?? "desconocida",
    isGM: Boolean(game.user?.isGM),
    eligibleAssets: KONA_TOKEN_ICON_BANK.length,
    excludedAssets: KONA_TOKEN_ICON_EXCLUDED_IDS.length
  });
  if (!game.user?.isGM) {
    console.warn(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] La asignación automática requiere permisos de GM.`);
  }
});

Hooks.on("createActor", actor => {
  if (!game.user?.isGM) return;
  konaTokenIconDebug("createActor detectado", {
    actorId: actor?.id, actorName: actor?.name, actorType: actor?.type,
    culture: actor?.system?.props?.cultura ?? actor?.system?.props?.culture ?? "",
    office: actor?.system?.props?.oficio ?? actor?.system?.props?.office ?? "",
    recognized: konaTokenIconIsKonaPJ(actor)
  });
  konaTokenIconSchedule("asignación tras crear actor", () => konaTokenIconEnsure(actor), actor);
});

Hooks.on("updateActor", (actor, changes) => {
  if (!game.user?.isGM || !konaTokenIconIsKonaPJ(actor)) return;
  const cultureChanged = konaTokenIconChanged(changes, "system.props.cultura") || konaTokenIconChanged(changes, "system.props.culture");
  const officeChanged = konaTokenIconChanged(changes, "system.props.oficio") || konaTokenIconChanged(changes, "system.props.office");
  if (!cultureChanged && !officeChanged) return;
  konaTokenIconSchedule("reconciliación por cambio real de Cultura/Oficio", () => konaTokenIconReconcileActor(actor), actor);
});

function konaTokenIconInstallSheetRefresh(application, html) {
  const actor = application?.actor ?? application?.document ?? null;
  const root = konaTokenIconHtmlRoot(html) ?? application?.element?.[0] ?? application?.element ?? null;
  const isKona = konaTokenIconIsKonaPJ(actor);
  const selectorFound = Boolean(root?.querySelector?.(".ha-kona-sheet"));
  konaTokenIconDebug("Diagnóstico render ficha", {
    hook: application?.constructor?.name ?? null,
    actorId: actor?.id ?? null,
    actorName: actor?.name ?? null,
    actorType: actor?.type ?? null,
    actorDocumentName: actor?.documentName ?? null,
    systemId: actor?.system?.id ?? actor?.system?.type ?? game.system?.id ?? null,
    systemKeys: actor?.system ? Object.keys(actor.system) : null,
    propsExists: Boolean(actor?.system?.props),
    propsKeys: actor?.system?.props ? Object.keys(actor.system.props) : null,
    cultura: actor?.system?.props?.cultura ?? null,
    culture: actor?.system?.props?.culture ?? null,
    oficio: actor?.system?.props?.oficio ?? null,
    office: actor?.system?.props?.office ?? null,
    isGM: Boolean(game.user?.isGM),
    isKona,
    htmlType: html?.constructor?.name ?? typeof html,
    htmlIsElement: typeof HTMLElement !== "undefined" && html instanceof HTMLElement,
    htmlFirstIsElement: typeof HTMLElement !== "undefined" && html?.[0] instanceof HTMLElement,
    applicationElementType: application?.element?.constructor?.name ?? null,
    rootType: root?.constructor?.name ?? null,
    rootClass: root?.className ?? null,
    rootId: root?.id ?? null,
    rootConnected: Boolean(root?.isConnected),
    rootHasQuerySelector: typeof root?.querySelector === "function",
    konaSheetCount: root?.querySelectorAll?.(".ha-kona-sheet")?.length ?? null,
    tokenDisplayCount: root?.querySelectorAll?.(".ha-kona-token-display")?.length ?? null
  });
  if (!game.user?.isGM || !isKona) {
    konaTokenIconDebug("Render omitido: no es GM o actor no Kona", { isGM: Boolean(game.user?.isGM), isKona });
    return;
  }
  if (!root) {
    console.warn(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] DIAG: no se pudo resolver la raíz de la ficha.`);
    return;
  }
  const canvas = root.matches?.(".ha-kona-sheet") ? root : root.querySelector?.(".ha-kona-sheet");
  if (!canvas) {
    console.warn(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] DIAG: raíz encontrada, pero no contiene .ha-kona-sheet.`, {
      rootClass: root.className ?? null,
      descendants: Array.from(root.querySelectorAll?.("[class]") ?? []).slice(0, 80).map(el => el.className).filter(Boolean)
    });
    return;
  }
  konaTokenIconInstallStyles();
  canvas.style.setProperty("position", "relative", "important");
  let display = canvas.querySelector(":scope > .ha-kona-token-display");
  if (!display) {
    display = document.createElement("div");
    display.className = "ha-kona-token-display";
    display.setAttribute("aria-label", "Token Kona");
    const image = document.createElement("img");
    image.className = "ha-kona-token-preview";
    image.alt = "Token del personaje";
    image.draggable = false;
    image.style.pointerEvents = "none";
    display.append(image);
    canvas.appendChild(display);
    konaTokenIconDebug("DIAG: contenedor e imagen estática insertados", {
      canvasClass: canvas.className ?? null,
      canvasConnected: Boolean(canvas.isConnected),
      displayConnected: Boolean(display.isConnected),
      childCount: canvas.children?.length ?? null
    });
  } else {
    konaTokenIconDebug("DIAG: contenedor de token ya existía", { displayConnected: Boolean(display.isConnected) });
  }
  // El propio token es el control: sin botón de regeneración.
  const image = display.querySelector(".ha-kona-token-preview");
  if (image && !image.dataset.konaHoverCycleBound) {
    image.dataset.konaHoverCycleBound = "true";
    image.tabIndex = 0;
    image.title = "Haz clic para elegir otro token Kona";
    image.setAttribute("role", "button");
    image.setAttribute("aria-label", "Elegir otro token Kona");
    const changeToken = async event => {
      event.preventDefault(); event.stopPropagation();
      // El candado original de capacidades gobierna también la generación Kona.
      // Si está activo, no hacer nada ni mostrar una notificación.
      if (konaTokenIconIsGenerationLocked(actor)) return;
      try {
        const currentId = actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_ID);
        const record = currentId ? konaTokenIconChooseReroll(actor) : konaTokenIconChooseInitial(actor);
        const applied = await konaTokenIconApply(actor, record, { mode: currentId ? "sheet-reroll" : "sheet-initial" });
        if (applied) { image.src = record.src; ui.notifications?.info?.("MELIAZ: token actualizado y sincronizado."); }
        else ui.notifications?.warn?.("MELIAZ: no se pudo actualizar el token. Comprueba permisos, tipo de actor y Cultura/Oficio.");
      } catch (error) { console.error(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] Falló el cambio de token desde la ficha.`, error); ui.notifications?.error?.("MELIAZ: falló el cambio de token. Revisa la consola."); }
    };
    image.addEventListener("click", changeToken);
    image.addEventListener("keydown", event => { if (event.key === "Enter" || event.key === " ") changeToken(event); });
  }

  const current = String(actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_PATH) ?? actor.img ?? "").trim();
  const previewImage = display.querySelector(".ha-kona-token-preview");
  const isLocked = Boolean(actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_LOCK));
  if (previewImage) {
    previewImage.classList.toggle("ha-kona-token-locked", isLocked);
    previewImage.title = isLocked ? "Token bloqueado: desbloquea la selección automática para cambiarlo" : "Pasa el cursor y haz clic para elegir otro token Kona";
    previewImage.setAttribute("aria-label", isLocked ? "Token Kona bloqueado" : "Elegir otro token Kona");
  }
  if (previewImage && current && previewImage.getAttribute("src") !== current) previewImage.src = current;
  konaTokenIconDebug("DIAG: resultado final de render", {
    currentImage: current || null,
    imageSrc: image?.getAttribute("src") ?? null,
    imageComplete: Boolean(image?.complete),
    imageNaturalWidth: image?.naturalWidth ?? null,
    imageNaturalHeight: image?.naturalHeight ?? null,
    imageConnected: Boolean(image?.isConnected),
    displayRect: display?.getBoundingClientRect?.().toJSON?.() ?? null,
    canvasRect: canvas?.getBoundingClientRect?.().toJSON?.() ?? null
  });
}

const konaTokenIconOnRenderActorSheet = (application, html) => {
  konaTokenIconInstallSheetRefresh(application, html);
  if (!game.user?.isGM) return;
  // Render de hoja estrictamente de lectura: no sincronizar ni escribir Actor aquí.
};
// V1 sheets use renderActorSheet; ApplicationV2 sheets use renderActorSheetV2.
Hooks.on("renderActorSheet", konaTokenIconOnRenderActorSheet);
Hooks.on("renderActorSheetV2", konaTokenIconOnRenderActorSheet);

Hooks.on("createToken", tokenDoc => {
  if (!game.user?.isGM) return;
  const actor = tokenDoc?.actor ?? tokenDoc?.parent?.actor ?? null;
  if (actor) konaTokenIconSchedule("sincronización al crear token", () => konaTokenIconEnsure(actor, tokenDoc), actor);
});

