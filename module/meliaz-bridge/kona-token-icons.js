function konaTokenIconDebug(message, details = undefined) {
  if (!KONA_TOKEN_ICON_DEBUG) return;
  if (details === undefined) console.info(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] ${message}`);
  else console.info(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] ${message}`, details);
}

const KONA_TOKEN_ICON_PENDING = new Map();
function konaTokenIconSchedule(label, callback, actor = null) {
  const key = actor?.uuid ?? actor?.id ?? "__global__";
  const current = KONA_TOKEN_ICON_PENDING.get(key);
  if (current) {
    // Coalesce repeated hooks; retain only the latest requested reconciliation.
    current.next = { label, callback, actor };
    return;
  }
  const state = { next: null };
  KONA_TOKEN_ICON_PENDING.set(key, state);
  queueMicrotask(async () => {
    try {
      let task = { label, callback, actor };
      do {
        state.next = null;
        await Promise.resolve().then(task.callback);
        task = state.next;
      } while (task);
    } catch (error) {
      console.error(`[MELIAZ KonaTokens ${KONA_TOKEN_ICON_BUILD}] ${label} falló.`, {
        actorId: actor?.id ?? null, actorName: actor?.name ?? null, error
      });
    } finally {
      KONA_TOKEN_ICON_PENDING.delete(key);
    }
  });
}

function konaTokenIconIsGenerationLocked(actor) {
  // El candado canónico de la hoja controla capacidades y generación Kona.
  // La bandera específica antigua se conserva solo como compatibilidad de lectura.
  return Boolean(
    actor?.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, "capacidadesLocked") ||
    actor?.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_LOCK)
  );
}

function konaTokenIconNormalize(value) {
  return String(value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

function konaTokenIconOfficeKey(value) {
  const key = konaTokenIconNormalize(value);
  if (key.startsWith("sabio") || key === "taita") return "sabio";
  if (key.startsWith("cantor") || key === "pueta") return "cantor";
  if (key.startsWith("viajero") || key === "patiperro") return "viajero";
  if (key.startsWith("guerrero") || key === "weichan") return "guerrero";
  return "";
}

function konaTokenIconActorCulture(actor) {
  const props = actor?.system?.props ?? {};
  const value = konaTokenIconNormalize(props.cultura ?? props.culture ?? "");
  if (!value) return "";
  const exact = KONA_TOKEN_ICON_BANK.find(record => record.cultureKey === value);
  if (exact) return exact.cultureKey;
  // Acepta etiquetas de interfaz como "Cultura Mapuche" sin crear nuevas culturas.
  const contained = KONA_TOKEN_ICON_BANK
    .filter(record => value.includes(record.cultureKey))
    .sort((a, b) => b.cultureKey.length - a.cultureKey.length)[0];
  return contained?.cultureKey ?? "";
}

function konaTokenIconActorOffice(actor) {
  const props = actor?.system?.props ?? {};
  return konaTokenIconOfficeKey(props.oficio ?? props.office ?? "");
}

function konaTokenIconIsKonaPJ(actor) {
  const props = actor?.system?.props;
  if (!actor || actor.documentName !== "Actor" || !props) return false;
  if (actor.type && actor.type !== "character") return false;
  // En la ficha real probada, Cultura puede estar vacía aunque el actor tenga
  // Oficio y Maestrías Kona válidas. No exigir Cultura para mostrar el token.
  const office = String(props.oficio ?? props.office ?? "").trim();
  const hasMastery = ["temple", "onda", "picardia", "neque"].some(key =>
    Object.prototype.hasOwnProperty.call(props, key) && props[key] !== undefined && props[key] !== null
  );
  return Boolean(office && hasMastery);
}

function konaTokenIconRandom(pool) {
  return pool.length ? pool[Math.floor(Math.random() * pool.length)] : null;
}

function konaTokenIconChooseInitial(actor) {
  const cultureKey = konaTokenIconActorCulture(actor);
  const officeKey = konaTokenIconActorOffice(actor);
  // Prioridad 1: coincidencia exacta Cultura + Oficio.
  if (cultureKey && officeKey) {
    const exact = KONA_TOKEN_ICON_BANK.find(record => record.cultureKey === cultureKey && record.officeKey === officeKey);
    if (exact) return exact;
  }
  // Prioridad 2: si no existe coincidencia exacta Cultura + Oficio, sortear dentro del Oficio.
  const officePool = officeKey ? KONA_TOKEN_ICON_BANK.filter(record => record.officeKey === officeKey) : [];
  if (officePool.length) return konaTokenIconRandom(officePool);
  // Prioridad 3: si no hay fichas del Oficio, probar el conjunto de la Cultura.
  const culturePool = cultureKey ? KONA_TOKEN_ICON_BANK.filter(record => record.cultureKey === cultureKey) : [];
  if (culturePool.length) return konaTokenIconRandom(culturePool);
  // Último recurso: sorteo general entre las fichas elegibles.
  return konaTokenIconRandom(KONA_TOKEN_ICON_BANK);
}

function konaTokenIconChooseReroll(actor) {
  const currentId = actor?.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_ID);
  const officeKey = konaTokenIconActorOffice(actor);
  const officePool = officeKey
    ? KONA_TOKEN_ICON_BANK.filter(record => record.officeKey === officeKey && record.id !== currentId)
    : [];
  if (officePool.length) return konaTokenIconRandom(officePool);
  const cultureKey = konaTokenIconActorCulture(actor);
  const culturePool = cultureKey
    ? KONA_TOKEN_ICON_BANK.filter(record => record.cultureKey === cultureKey && record.id !== currentId)
    : [];
  if (culturePool.length) return konaTokenIconRandom(culturePool);
  const pool = KONA_TOKEN_ICON_BANK.filter(record => record.id !== currentId);
  return konaTokenIconRandom(pool.length ? pool : KONA_TOKEN_ICON_BANK);
}

function konaTokenIconTokenSrc(tokenDoc) {
  return String(tokenDoc?.texture?.src ?? tokenDoc?._source?.texture?.src ?? "").trim();
}

function konaTokenIconPrototypeSrc(actor) {
  return String(actor?.prototypeToken?.texture?.src ?? "").trim();
}

function konaTokenIconChanged(changes, path) {
  if (!changes || typeof changes !== "object") return false;
  if (Object.prototype.hasOwnProperty.call(changes, path)) return true;
  let current = changes;
  for (const part of path.split(".")) {
    if (!current || typeof current !== "object" || !Object.prototype.hasOwnProperty.call(current, part)) return false;
    current = current[part];
  }
  return true;
}

async function konaTokenIconApply(actor, record, { tokenDoc = null, mode = "culture-office", forceSync = false } = {}) {
  if (!game.user?.isGM || !konaTokenIconIsKonaPJ(actor) || !record) return false;
  if (konaTokenIconIsGenerationLocked(actor)) return false;

  // One selected image is intentionally shared by the actor portrait, prototype token,
  // and all placed scene tokens. This is the current Kona LAB behavior.
  const update = {
    img: record.src,
    "prototypeToken.texture.src": record.src,
    [`flags.${KONA_TOKEN_ICON_MODULE_ID}.${KONA_TOKEN_ICON_FLAG_PATH}`]: record.src,
    [`flags.${KONA_TOKEN_ICON_MODULE_ID}.${KONA_TOKEN_ICON_FLAG_ID}`]: record.id,
    [`flags.${KONA_TOKEN_ICON_MODULE_ID}.konaTokenIconCulture`]: record.culture,
    [`flags.${KONA_TOKEN_ICON_MODULE_ID}.konaTokenIconOffice`]: record.office,
    [`flags.${KONA_TOKEN_ICON_MODULE_ID}.konaTokenIconMode`]: mode
  };
  const actorImg = String(actor?.img ?? actor?._source?.img ?? "").trim();
  const prototypeSrc = konaTokenIconPrototypeSrc(actor);
  const previousPath = String(actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_PATH) ?? "");
  const previousId = actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_ID);
  const needsActorUpdate = actorImg !== record.src || prototypeSrc !== record.src || previousPath !== record.src || previousId !== record.id;
  if (needsActorUpdate) await actor.update(update, { render: false });

  // Keep already placed tokens in sync, including tokens whose image was originally
  // created by Tokenizer. Kona's selected icon is the authoritative image for this LAB.
  const candidates = new Set();
  for (const doc of Array.from(canvas?.scene?.tokens ?? [])) {
    if (doc?.actorId === actor.id || doc?.actor?.id === actor.id) candidates.add(doc);
  }
  if (tokenDoc) candidates.add(tokenDoc);
  for (const doc of candidates) {
    const source = konaTokenIconTokenSrc(doc);
    if (source === record.src) continue;
    try {
      await doc.update({ "texture.src": record.src }, { render: false });
    } catch (error) {
      console.warn("MELIAZ Bridge · Kona token LAB: no pude actualizar una ficha de escena.", error);
    }
  }
  return true;
}

async function konaTokenIconEnsure(actor, tokenDoc = null) {
  if (!game.user?.isGM || !konaTokenIconIsKonaPJ(actor)) return false;
  const previousPath = String(actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_PATH) ?? "");
  const previousId = actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_ID);
  if (previousPath) {
    const selected = KONA_TOKEN_ICON_BANK.find(record => record.id === previousId);
    if (!selected) return false;
    const actorImg = String(actor?.img ?? actor?._source?.img ?? "").trim();
    const protoSrc = konaTokenIconPrototypeSrc(actor);
    const tokenSrc = konaTokenIconTokenSrc(tokenDoc);
    if (actorImg === selected.src && protoSrc === selected.src && (!tokenDoc || tokenSrc === selected.src)) return true;
    return konaTokenIconApply(actor, selected, {
      tokenDoc,
      mode: actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, "konaTokenIconMode") ?? "culture-office",
      forceSync: true
    });
  }
  if (konaTokenIconIsGenerationLocked(actor)) return false;
  return konaTokenIconApply(actor, konaTokenIconChooseInitial(actor), { tokenDoc, mode: "culture-office" });
}

async function konaTokenIconReconcileActor(actor) {
  if (!game.user?.isGM || !konaTokenIconIsKonaPJ(actor)) return;
  if (konaTokenIconIsGenerationLocked(actor)) return;
  const selected = konaTokenIconChooseInitial(actor);
  if (!selected) return;
  const currentId = actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_ID);
  const currentPath = String(actor.getFlag?.(KONA_TOKEN_ICON_MODULE_ID, KONA_TOKEN_ICON_FLAG_PATH) ?? "");
  const actorImg = String(actor?.img ?? actor?._source?.img ?? "").trim();
  const prototypeSrc = konaTokenIconPrototypeSrc(actor);
  if (selected.id === currentId && selected.src === currentPath && actorImg === selected.src && prototypeSrc === selected.src) return;
  await konaTokenIconApply(actor, selected, { mode: "culture-office" });
}

function konaTokenIconHtmlRoot(html) {
  if (typeof HTMLElement !== "undefined" && html instanceof HTMLElement) return html;
  if (html?.[0] && typeof HTMLElement !== "undefined" && html[0] instanceof HTMLElement) return html[0];
  if (html?.element && typeof HTMLElement !== "undefined" && html.element instanceof HTMLElement) return html.element;
  return null;
}

